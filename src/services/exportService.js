import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';

/**
 * Export and Print Utilities
 * Supports exporting analysis reports to PDF, saving resume as PDF,
 * and downloading JSON audit data.
 */
export const ExportService = {
  // Export analysis summary as printable PDF
  async exportAnalysisReport(elementId, fileName = 'ResumeXray_Report.pdf') {
    const element = document.getElementById(elementId);
    if (!element) {
      window.print();
      return;
    }

    try {
      const canvas = await html2canvas(element, {
        scale: 2,
        useCORS: true,
        logging: false,
        backgroundColor: '#FFFFFF'
      });

      const imgData = canvas.toDataURL('image/png');
      const pdf = new jsPDF('p', 'mm', 'a4');
      const imgWidth = 210; // A4 mm
      const pageHeight = 295;
      const imgHeight = (canvas.height * imgWidth) / canvas.width;
      let heightLeft = imgHeight;
      let position = 0;

      pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight);
      heightLeft -= pageHeight;

      while (heightLeft >= 0) {
        position = heightLeft - imgHeight;
        pdf.addPage();
        pdf.addImage(imgData, 'PNG', 0, position, imgWidth, imgHeight);
        heightLeft -= pageHeight;
      }

      pdf.save(fileName);
    } catch (err) {
      console.warn('html2canvas PDF export issue, invoking native browser print:', err);
      window.print();
    }
  },

  // Export raw analysis JSON for verification or auditing
  exportJsonData(data, fileName = 'resumexray_data.json') {
    const jsonString = `data:text/json;charset=utf-8,${encodeURIComponent(JSON.stringify(data, null, 2))}`;
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute('href', jsonString);
    downloadAnchor.setAttribute('download', fileName);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
  },

  // Copy structured markdown report to clipboard
  async copyReportMarkdown(analysis) {
    if (!analysis) return;
    const md = `
# ResumeXray Intelligence Report: ${analysis.targetRoleTitle || 'Career Analysis'}
*Analyzed on ${new Date(analysis.analyzedAt).toLocaleDateString()}*

## 📊 Scores Overview
- **Overall Resume Score**: ${analysis.scores?.overall || 0}/100
- **ATS Compatibility**: ${analysis.scores?.ats || 0}/100
- **Skills Match**: ${analysis.scores?.skills || 0}/100
- **Experience Quality**: ${analysis.scores?.experience || 0}/100
- **Keywords Coverage**: ${analysis.scores?.keywords || 0}/100

## 🛠️ Extracted Skills (${analysis.skills?.totalCount || 0})
${analysis.skills?.allFound?.join(', ') || 'None'}

## 🎯 Top Priority Improvements
${(analysis.recommendations || []).slice(0, 4).map(r => `- **[${r.priority}] ${r.title}**: ${r.explanation}`).join('\n')}

---
*Generated by ResumeXray Frontend Prototype*
    `.trim();

    try {
      await navigator.clipboard.writeText(md);
      return true;
    } catch {
      return false;
    }
  }
};
